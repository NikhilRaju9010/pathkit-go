package soundness

import (
	"fmt"
	"strings"
)

// File returns the whole Go file for a batch of programs: the helpers they
// call, then each function.
func File(programs []Program) string {
	var b strings.Builder
	b.WriteString(`// Code generated by internal/soundness; DO NOT EDIT.
package progs

import "go.temporal.io/sdk/workflow"

func noop() {}

func sp(s string) *string { return &s }

// normalise stands for "any call PathKit cannot see into".
func normalise(s string) string { return s + "" }

// touch takes the address of a string, like Get(ctx, &x) does.
func touch(p *string, in string) {
	if in != "" {
		*p = in
	}
}
`)
	for _, p := range programs {
		b.WriteString("\n")
		b.WriteString(p.Source)
	}
	return b.String()
}

// DriverTest returns a _test.go file that runs every program once for each
// of its inputs in the Temporal test environment.
func DriverTest(programs []Program) string {
	var b strings.Builder
	b.WriteString(`package progs

import (
	"testing"

	"go.temporal.io/sdk/testsuite"
)

func TestRunAll(t *testing.T) {
	var suite testsuite.WorkflowTestSuite
	run := func(name string, fn interface{}, args ...interface{}) {
		env := suite.NewTestWorkflowEnvironment()
		env.ExecuteWorkflow(fn, args...)
		if !env.IsWorkflowCompleted() {
			t.Fatalf("%s %v: not completed", name, args)
		}
		if err := env.GetWorkflowError(); err != nil {
			t.Fatalf("%s %v: %v", name, args, err)
		}
	}
`)
	for _, p := range programs {
		for _, in := range p.Inputs {
			fmt.Fprintf(&b, "\trun(%q, %s, %s)\n", p.Name, p.Name, in)
		}
	}
	b.WriteString("}\n")
	return b.String()
}
