package soundness

import (
	"fmt"
	"strings"
)

// File returns the whole Go file for a batch of programs: the helpers they
// call, then each function.
func File(programs []Program) string {
	var b strings.Builder
	b.WriteString(`// Code generated by internal/soundness; DO NOT EDIT.
package progs

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"time"

	"go.temporal.io/sdk/temporal"
	"go.temporal.io/sdk/workflow"
)

var _ = temporal.IsCanceledError
var _ = errors.New
var _ = bytes.NewReader
var _ = context.Background
var _ json.Number
var _ = time.Second

func noop() {}

// ActEcho is an activity that receives a map: the SDK hands it a decoded copy,
// so whatever it does to the map is not seen by the workflow.
func ActEcho(ctx context.Context, m map[string]interface{}) error {
	if m != nil {
		m["k"] = 99
	}
	return nil
}

// LocalSet is a local activity: it gets the very map the workflow holds.
func LocalSet(ctx context.Context, m map[string]interface{}) error {
	if m != nil {
		m["k"] = 5
	}
	return nil
}

// pair2 stands for a call that is not Temporal's and may fail.
func pair2(n int) error {
	if n == 1 {
		return errors.New("one")
	}
	return nil
}

// Rec is a struct held by value; Flagged is a named bool type.
type Rec struct {
	A  string
	B  int
	C  bool
	In struct{ ID string }
}

func (r *Rec) setA(s string) { r.A = s }

type Flagged bool

// actInput wraps a map in a struct handed to an activity.
type actInput struct{ Data map[string]interface{} }

func sp(s string) *string { return &s }

// pair stands for a call with two results PathKit cannot see into.
func pair(s string) (interface{}, error) {
	if s == "" {
		return 7, nil
	}
	return s, nil
}

// mutateAny writes an int into a map that an interface holds.
func mutateAny(v interface{}) {
	if m, ok := v.(map[string]interface{}); ok && m != nil {
		m["a"] = 5
	}
}

// mutate stores an int in a map; mutateS in a slice (if it has an element).
func mutate(m map[string]interface{}) {
	if m != nil {
		m["a"] = 1
	}
}

func mutateS(s []interface{}) {
	if len(s) > 0 {
		s[0] = 1
	}
}

// normalise stands for "any call PathKit cannot see into".
func normalise(s string) string { return s + "" }

// touch takes the address of a string, like Get(ctx, &x) does.
func touch(p *string, in string) {
	if in != "" {
		*p = in
	}
}
`)
	for _, p := range programs {
		b.WriteString("\n")
		b.WriteString(p.Source)
	}
	return b.String()
}

// DriverTest returns a _test.go file that runs every program once for each
// of its inputs in the Temporal test environment.
func DriverTest(programs []Program) string {
	var b strings.Builder
	b.WriteString(`package progs

import (
	"testing"

	"go.temporal.io/sdk/testsuite"
)

func TestRunAll(t *testing.T) {
	var suite testsuite.WorkflowTestSuite
	run := func(name string, fn interface{}, args ...interface{}) {
		env := suite.NewTestWorkflowEnvironment()
		env.RegisterActivity(ActEcho)
		env.ExecuteWorkflow(fn, args...)
		if !env.IsWorkflowCompleted() {
			t.Fatalf("%s %v: not completed", name, args)
		}
		if err := env.GetWorkflowError(); err != nil {
			t.Fatalf("%s %v: %v", name, args, err)
		}
	}
`)
	for _, p := range programs {
		for _, in := range p.Inputs {
			fmt.Fprintf(&b, "\trun(%q, %s, %s)\n", p.Name, p.Name, in)
		}
	}
	b.WriteString("}\n")
	return b.String()
}
