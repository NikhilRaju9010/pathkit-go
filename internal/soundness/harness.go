package soundness

import (
	"fmt"
	"strings"
)

// File returns the whole Go file for a batch of programs: the helpers they
// call, then each function.
func File(programs []Program) string {
	var b strings.Builder
	b.WriteString(`// Code generated by internal/soundness; DO NOT EDIT.
package progs

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"time"

	"go.temporal.io/sdk/temporal"
	"go.temporal.io/sdk/workflow"
)

var _ = temporal.IsCanceledError
var _ = errors.New
var _ = bytes.NewReader
var _ = context.Background
var _ json.Number
var _ = time.Second

func noop() {}

// ActEcho is an activity that receives a map: the SDK hands it a decoded copy,
// so whatever it does to the map is not seen by the workflow.
func ActEcho(ctx context.Context, m map[string]interface{}) error {
	if m != nil {
		m["k"] = 99
	}
	return nil
}

// LocalSet is a local activity: it gets the very map the workflow holds.
func LocalSet(ctx context.Context, m map[string]interface{}) error {
	if m != nil {
		m["k"] = 5
	}
	return nil
}

// pair2 stands for a call that is not Temporal's and may fail.
func pair2(n int) error {
	if n == 1 {
		return errors.New("one")
	}
	return nil
}

// Rec is a struct held by value; Flagged is a named bool type.
type Rec struct {
	A  string
	B  int
	C  bool
	In struct{ ID string }
}

func (r *Rec) setA(s string) { r.A = s }

type Flagged bool

// actInput wraps a map in a struct handed to an activity.
type actInput struct{ Data map[string]interface{} }

func sp(s string) *string { return &s }

// pair stands for a call with two results PathKit cannot see into.
func pair(s string) (interface{}, error) {
	if s == "" {
		return 7, nil
	}
	return s, nil
}

// mutateAny writes an int into a map that an interface holds.
func mutateAny(v interface{}) {
	if m, ok := v.(map[string]interface{}); ok && m != nil {
		m["a"] = 5
	}
}

// mutate stores an int in a map; mutateS in a slice (if it has an element).
func mutate(m map[string]interface{}) {
	if m != nil {
		m["a"] = 1
	}
}

func mutateS(s []interface{}) {
	if len(s) > 0 {
		s[0] = 1
	}
}

// normalise stands for "any call PathKit cannot see into".
func normalise(s string) string { return s + "" }

// touch takes the address of a string, like Get(ctx, &x) does.
func touch(p *string, in string) {
	if in != "" {
		*p = in
	}
}
`)
	for _, p := range programs {
		b.WriteString("\n")
		b.WriteString(p.Source)
	}
	return b.String()
}

// retrySource is the one rule for a program that fails in the generated driver:
// only Temporal's deadlock alarm ("Potential deadlock detected", error code
// TMPRL1101: a workflow goroutine did not yield for too long, which a stalled
// machine can cause) earns one more attempt from scratch, and the attempt is
// recorded; any other error, or a second alarm, is a failure. It is plain Go so
// a test can compile and run exactly this text.
const retrySource = `
// runWithRetry runs attempt, and once more when it ended with the deadlock alarm
// (note records that); it returns what went wrong in the last attempt, "" if
// nothing did.
func runWithRetry(attempt func() string, note func()) string {
	msg := attempt()
	if msg != "" && strings.Contains(msg, "Potential deadlock detected") {
		note()
		msg = attempt()
	}
	return msg
}
`

// DriverTest returns a _test.go file that runs every program once for each
// of its inputs in the Temporal test environment.
func DriverTest(programs []Program) string {
	var b strings.Builder
	b.WriteString(`package progs

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"go.temporal.io/sdk/activity"
	"go.temporal.io/sdk/converter"
	"go.temporal.io/sdk/testsuite"
	"go.temporal.io/sdk/worker"
)

// traceFiles lists the trace files in dir (PK_TRACES), to find the one a run
// wrote.
func traceFiles(dir string) map[string]bool {
	out := map[string]bool{}
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		if strings.HasSuffix(e.Name(), ".trace.json") {
			out[e.Name()] = true
		}
	}
	return out
}

` + retrySource + `
func TestRunAll(t *testing.T) {
	var suite testsuite.WorkflowTestSuite
	dir := os.Getenv("PK_TRACES")
	// attempt runs one program once, from scratch, and says what went wrong ("" when
	// nothing did). A failed attempt leaves no trace file behind.
	attempt := func(fn interface{}, args ...interface{}) string {
		env := suite.NewTestWorkflowEnvironment()
		// generated programs only: the default alarm (1 second without yielding)
		// can fire when the machine stalls
		env.SetWorkerOptions(worker.Options{DeadlockDetectionTimeout: 5 * time.Second})
		env.RegisterActivity(ActEcho)
		// what the run does outside the workflow, in order: activities, local
		// activities and timers; written next to the run's trace file
		var events []string
		env.SetOnActivityStartedListener(func(info *activity.Info, _ context.Context, _ converter.EncodedValues) {
			events = append(events, "A:"+info.ActivityType.Name)
		})
		env.SetOnLocalActivityStartedListener(func(info *activity.Info, _ context.Context, _ []interface{}) {
			events = append(events, "L:"+info.ActivityType.Name)
		})
		env.SetOnTimerScheduledListener(func(string, time.Duration) { events = append(events, "T") })
		before := traceFiles(dir)
		env.ExecuteWorkflow(fn, args...)
		msg := ""
		if !env.IsWorkflowCompleted() {
			msg = "not completed"
		} else if err := env.GetWorkflowError(); err != nil {
			msg = err.Error()
		}
		for f := range traceFiles(dir) {
			if before[f] {
				continue
			}
			if msg != "" {
				_ = os.Remove(filepath.Join(dir, f))
				continue
			}
			_ = os.WriteFile(filepath.Join(dir, f+".events"), []byte(strings.Join(events, "\n")), 0o644)
		}
		return msg
	}
	run := func(name string, fn interface{}, args ...interface{}) {
		msg := runWithRetry(func() string { return attempt(fn, args...) }, func() {
			f, err := os.OpenFile(filepath.Join(dir, "deadlock-reruns.log"), os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
			if err == nil {
				_, _ = f.WriteString(name + "\n")
				_ = f.Close()
			}
		})
		if msg != "" {
			t.Fatalf("%s %v: %s", name, args, msg)
		}
	}
`)
	for _, p := range programs {
		for _, in := range p.Inputs {
			fmt.Fprintf(&b, "\trun(%q, %s, %s)\n", p.Name, p.Name, in)
		}
	}
	b.WriteString("}\n")
	return b.String()
}
